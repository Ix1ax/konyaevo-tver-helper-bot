package dev.ix1ax.main.bot;

/** Общая справка для команды и кнопки «Помощь». */
public final class HelpText {
    private HelpText() {}

    public static String forUser(boolean admin) {
        String text = """
                ❔ <b>Помощь</b>

                /start — открыть меню и выбрать Вашу группу или преподавателя.
                /help — открыть эту справку.
                /cancel — отменить ввод времени или подготовку рассылки и вернуться в меню.

                <b>Сегодня и завтра</b> — пары выбранной группы или преподавателя с учётом опубликованных замен. Отменённые пары отмечены отдельно.
                <b>Неделя</b> — основное расписание по дням текущей недели, без замен и отмен.
                <b>Замены</b> — изменения для Вашей группы или преподавателя.
                <b>Уведомления</b> — включение замен и расписания на завтра, выбор дней и времени по Москве. Настройки общие с миниапкой.
                <b>Сменить группу / преподавателя / роль</b> — выбрать другое расписание.

                В разделе «Неделя» миниапки показывается основное расписание без замен и отмен.
                В миниапке доступны поиск преподавателей, свободные кабинеты и настройки профиля. Свободные кабинеты рассчитываются по основному расписанию, без замен.
                """;
        if (admin) text += """

                🛠 <b>Администратору</b>
                /admin — панель управления.
                /stats — пользователи, активность и подписки.
                /refresh — обновить данные расписания и замен.
                /broadcast текст — подготовить текстовую рассылку.
                /broadcast — затем прикрепите одно фото, видео, GIF или документ с подписью. Можно также ответить этой командой на медиа. Отправка всем выполняется только после подтверждения.
                В профиле миниапки доступны состояние данных, общие замены, статистика и отзывы с пагинацией.
                """;
        return text;
    }
}
